// Builds dist/.htaccess for Apache/LiteSpeed hosts such as Hostinger, which ignore _redirects:
// forces HTTPS without www, serves the custom 404, sets cache headers and applies the same
// redirect list as _redirects (see redirecionamentos.mjs).

import { url } from './url.mjs';

// mod_rewrite compares the decoded path, without the leading slash, to the pattern
const pattern = (de) => {
  let path = de.replace(/^\//, '');
  try {
    path = decodeURIComponent(path);
  } catch {
    // Keep the path as written when it is not valid percent-encoding
  }
  return `^${path.replace(/[\\^$.*+?()[\]{}|]/g, '\\$&').replace(/ /g, '\\x20')}$`;
};

// In the substitution "%N" and "$N" are back-references; NE keeps %XX and # as written
const target = (para) => para.replace(/[%$]/g, '\\$&');

const rule = (r) => `RewriteRule "${pattern(r.de)}" "${target(r.para)}" [R=${r.status},L,NE]`;

export const formatHtaccess = (list) => `# Generated by the build (astro.config.mjs): edits here are lost on the next deploy

Options -Indexes
AddDefaultCharset UTF-8
ErrorDocument 404 ${url('/404.html')}

# State file of the FTP deploy (.github/workflows/hostinger.yml)
<Files ".ftp-deploy-sync-state.json">
  Require all denied
</Files>

RewriteEngine On

# HTTPS and no www
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} ^www\\. [NC]
RewriteCond %{HTTP_HOST} ^(?:www\\.)?(.+)$ [NC]
RewriteRule ^ https://%1%{REQUEST_URI} [R=301,L,NE]

# Old addresses (same list as _redirects)
${list.map(rule).join('\n')}

<IfModule mod_headers.c>
  # Pages always revalidate, so a deploy shows up at once
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  # CSS, JS and fonts only live in /_astro/ with a hash in the name
  <FilesMatch "\\.(css|js|woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  # Product photos keep their name when replaced, so they get a shorter cache
  <FilesMatch "\\.(webp|avif|jpe?g|png|gif|svg|ico)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml
</IfModule>
`;
